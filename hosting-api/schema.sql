CREATE TABLE IF NOT EXISTS ecogrocer_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_code VARCHAR(24) NOT NULL,
  customer_name VARCHAR(80) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  area_id VARCHAR(40) NOT NULL,
  area_name VARCHAR(120) NOT NULL,
  block_name VARCHAR(40) NOT NULL,
  road_name VARCHAR(40) NOT NULL,
  house_number VARCHAR(60) NOT NULL,
  full_address VARCHAR(500) NOT NULL,
  delivery_slot VARCHAR(20) NOT NULL,
  notes VARCHAR(500) NULL,
  payment_method VARCHAR(16) NOT NULL,
  payer_phone VARCHAR(20) NULL,
  transaction_id VARCHAR(80) NULL,
  coupon_code VARCHAR(30) NULL,
  items_json LONGTEXT NOT NULL,
  subtotal DECIMAL(10,2) NOT NULL,
  delivery_charge DECIMAL(10,2) NOT NULL DEFAULT 0,
  discount DECIMAL(10,2) NOT NULL DEFAULT 0,
  grand_total DECIMAL(10,2) NOT NULL,
  order_status VARCHAR(20) NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ecogrocer_order_code (order_code),
  KEY idx_ecogrocer_phone (phone),
  KEY idx_ecogrocer_created_at (created_at),
  KEY idx_ecogrocer_status (order_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
